export function monthName(monthNumber) {
  return MONTHS[currentLang][Number(monthNumber) - 1] || '';
}

export function periodLabel(period) {
  const [y, m] = String(period || '').split('-');
  if (!y || !m) return period || '';
  return `${monthName(Number(m))} ${y}`;
}

