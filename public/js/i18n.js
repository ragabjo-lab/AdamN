let currentLang = localStorage.getItem('adamn.lang') || 'ar';

export function getLang() { return currentLang; }
export function isRTL() { return currentLang === 'ar'; }

export function setLang(lang, { persist = true } = {}) {
  currentLang = lang === 'en' ? 'en' : 'ar';
  if (persist) localStorage.setItem('adamn.lang', currentLang);
  document.documentElement.lang = currentLang;
  document.documentElement.dir = isRTL() ? 'rtl' : 'ltr';
  document.title = currentLang === 'ar' ? 'AdamN — نظام إدارة الحضانة' : 'AdamN — Nursery Management System';
  return currentLang;
}

export function t(key, fallback) {
  const entry = DICT[key];
  if (!entry) return fallback !== undefined ? fallback : key;
  return currentLang === 'en' ? entry[1] : entry[0];
}

/** Picks the localized value from a {ar, en} pair coming from the API. */
export function pick(arValue, enValue) {
  return currentLang === 'en' ? (enValue || arValue) : (arValue || enValue);
}

export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.getAttribute('data-i18n');
    const text = t(key, null);
    if (text) node.textContent = text;
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const key = node.getAttribute('data-i18n-placeholder');
    const text = t(key, null);
    if (text) node.setAttribute('placeholder', text);
  });
  root.querySelectorAll('[data-i18n-title]').forEach((node) => {
    const key = node.getAttribute('data-i18n-title');
    const text = t(key, null);
    if (text) node.setAttribute('title', text);
  });
}

